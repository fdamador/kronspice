"""PDF report for examples/scalar_disc: the optically gated rotating disc (H47 step 4)

Run from the repository root:

    python examples/scalar_disc/viz/make_report.py examples/scalar_disc/scalar_disc_report.pdf

The body is examples/scalar_disc/README.md rendered as written (internal/pdfreport/mdreport.py),
followed by any figures in viz/ it does not show and the head of run_output.txt.
Nothing is re-simulated. Layout from internal/pdfreport/kronreport.py.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EX = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "internal", "pdfreport"))
from kronreport import Report  # noqa: E402
from mdreport import add_figures, add_run_excerpt, render_markdown  # noqa: E402


def build(out):
    r = Report("examples/scalar_disc", "The optically gated rotating disc: a bench test of the scalar S", "Iadicicco and Verolino's falsifiable test of the scalar part of Maxwell's quaternion equations", "register entry H47 (step 4)")
    used = render_markdown(r, os.path.join(EX, "README.md"), base=EX)
    add_figures(r, os.path.join(EX, "viz"), skip=used)
    add_run_excerpt(r, os.path.join(EX, "run_output.txt"))
    r.h1("Reproducing the results")
    r.code("go run ./examples/scalar_disc\ngo test ./examples/scalar_disc")
    r.build(out)


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else os.path.join(EX, "scalar_disc_report.pdf"))
